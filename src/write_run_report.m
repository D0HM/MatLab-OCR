function write_run_report(results,summary,outDir)
% WRITE_RUN_REPORT A factual generated report; no invented experimental scores.
lines=["# Experiment results"; ""; ...
    "Generated from completed MATLAB runs. See config.json and environment.json."; ...
    "ocr = localization of recognized words; mser = independent candidate detection."; ...
    "Confidence is OCR confidence, not measured accuracy. CER/WER can exceed 1."; ...
    "Draft annotations are NOT scored. NaN means unavailable, not zero accuracy."; ...
    "The seven provided images are a case study, not a held-out benchmark."; ...
    "F1/F2 perform the required frequency-domain preprocessing; M0 is a baseline."; ...
    "Synthetic-demo results do not establish real-world performance."; ""; ...
    "| Detector | Method | Texture | Images | Scored | Confidence | Recognition % | F1 | CER | WER |"; ...
    "|---|---|---|---:|---:|---:|---:|---:|---:|---:|"];
for k=1:height(summary)
    r=summary(k,:);
    lines(end+1)=string(sprintf('| %s | %s | %s | %d | %d | %.3f | %.2f | %.3f | %.3f | %.3f |', ...
        r.Detector,r.Method,r.Texture,r.Images,r.ScoredImages,r.AvgConfidence, ...
        r.RecognitionRatePct,r.DetF1,r.CER,r.WER)); %#ok<AGROW>
end
lines=[lines; ""; "## Review low-scoring images"; ...
    "Check ocr_results.csv (EVERY returned box), image_results.csv and images/*/comparison.png."; ...
    "Check images/*/frequency_comparison.png for spectra and transfer functions."; ...
    "Green = GT, yellow = candidates, cyan = recognized words."; ""; ...
    "## Discussion prompts"; ...
    "- Which methods improve texture-specific performance, and which damage strokes?"; ...
    "- Are errors caused by localization, merged words, polarity or recognition?"; ...
    "- Does high confidence accompany incorrect text?"; ...
    "- Are labels reviewed? Are cut-off/rotated words included consistently?"; ...
    "- Were parameters selected on these same images? If yes, do not claim held-out performance."];
write_text(fullfile(outDir,'REPORT.md'),strjoin(lines,newline));
save(fullfile(outDir,'results.mat'),'results','summary');
end
